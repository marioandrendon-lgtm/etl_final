-- ============================================================
-- 8. DIA TIPO ACTUAL
-- La versión más reciente CARGADA gana por fecha.
-- ============================================================
create or replace view consulta.dim_dia_tipo_actual as
select distinct on (dt.fecha)
    dt.fecha,
    dt.dia_tipo,
    dt.dia_tipo_origen,
    d.id as dataset_id,
    a.id as archivo_id,
    a.nombre_archivo,
    dt.cargado_en
from bronze.dia_tipo dt
join carga.dataset_etl d on d.id = dt.dataset_id
join carga.archivo_etl a on a.id = d.archivo_id
where d.estado = 'CARGADO'
  and a.estado in ('CARGADO','CARGADO_PARCIAL')
order by dt.fecha, dt.cargado_en desc, dt.id desc;

-- ============================================================
-- 9. USOS VALIDADOR + DIA TIPO
-- ============================================================
create or replace view consulta.usos_validador_enriquecido as
select
    uv.id,
    uv.fecha,
    dt.dia_tipo,
    uv.estacion,
    uv.veh_id,
    uv.usos_validador,
    uv.dataset_id,
    d.archivo_id,
    a.nombre_archivo,
    uv.cargado_en
from bronze.usos_validador uv
join carga.dataset_etl d on d.id = uv.dataset_id
join carga.archivo_etl a on a.id = d.archivo_id
left join consulta.dim_dia_tipo_actual dt
    on dt.fecha = uv.fecha
where d.estado = 'CARGADO';

-- ============================================================
-- 10. RESUMEN DIARIO
-- ============================================================
create or replace view consulta.resumen_usos_validador_dia as
select
    fecha,
    dia_tipo,
    count(*) as registros,
    sum(coalesce(usos_validador,0)) as total_usos_dia
from consulta.usos_validador_enriquecido
group by fecha, dia_tipo;

-- ============================================================
-- 11. USOS EN FORMATO LARGO
-- ============================================================
create or replace view consulta.usos_hora as
select
    u.id as usos_id,
    u.fecha,
    u.estacion,
    v.hora,
    v.usos,
    u.dataset_id,
    d.archivo_id,
    a.nombre_archivo
from bronze.usos u
join carga.dataset_etl d on d.id = u.dataset_id
join carga.archivo_etl a on a.id = d.archivo_id
cross join lateral (
    values
        (1,u.h1),(2,u.h2),(3,u.h3),(4,u.h4),(5,u.h5),(6,u.h6),
        (7,u.h7),(8,u.h8),(9,u.h9),(10,u.h10),(11,u.h11),(12,u.h12),
        (13,u.h13),(14,u.h14),(15,u.h15),(16,u.h16),(17,u.h17),(18,u.h18),
        (19,u.h19),(20,u.h20),(21,u.h21),(22,u.h22),(23,u.h23)
) as v(hora, usos)
where d.estado = 'CARGADO';

-- ============================================================
-- 12. AUDITORÍA
-- ============================================================
create or replace view consulta.auditoria_archivos as
select
    a.id as archivo_id,
    a.nombre_archivo,
    a.tipo_archivo,
    a.sha256_archivo,
    a.fecha_archivo,
    a.estado as estado_archivo,
    d.id as dataset_id,
    d.tipo_dataset,
    d.sha256_contenido,
    d.estado as estado_dataset,
    d.filas_leidas,
    d.filas_cargadas,
    d.filas_rechazadas,
    d.fecha_min,
    d.fecha_max,
    a.iniciado_en,
    a.finalizado_en
from carga.archivo_etl a
left join carga.dataset_etl d
    on d.archivo_id = a.id;
